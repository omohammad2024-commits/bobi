/**
 * generate_image — render one image from a text prompt.
 *
 * SECURITY MODEL (read before touching the transport code):
 * - The prompt is USER DATA (model-controlled). It is sent ONLY to the image
 *   endpoint the owner configured (`BOBI_IMAGE_BASE_URL`), never anywhere the
 *   prompt itself could name. The URL is built from the owner config; no part
 *   of the model input can influence the host, path, or scheme.
 * - All HTTP goes through `resolveTarget` + `pinnedFetch`, the same pinned
 *   transport the AI adapters use: DNS is resolved and every address
 *   classified against the SSRF policy before any socket is opened, redirects
 *   are never followed, and the connection is bound to the approved addresses
 *   only. Local/private targets are refused (no local-target opt-in here).
 * - The API key is read from owner config and sent only as an Authorization
 *   header to the configured endpoint. Errors never echo the key or the raw
 *   response body — a provider that echoes the request must not be able to
 *   leak the key into a user-visible message.
 * - The generated bytes are PROVIDER OUTPUT treated as data. They are NEVER
 *   placed in `data` (the model-safe result): the base64 rides out-of-band via
 *   `extractMedia`, which the bot layer delivers to the user. `data` carries
 *   only metadata (prompt, size, optional revised prompt).
 * - One image per call (n=1), a per-call 90s deadline, and HTTP 429 maps to
 *   `overloaded` so the agent loop backs off instead of hammering the service.
 */
import { resolveTarget, type DnsResolver } from "../ai/dns_guard";
import { pinnedFetch } from "../ai/pinned_transport";
import { AiError } from "../ai/provider";
import { ToolError } from "./errors";
import type { Tool, ToolContext } from "./types";

export const GENERATE_IMAGE_PERMISSION = "tools:generate_image";

/** Sizes the images endpoint accepts (OpenAI images API shape). */
export type ImageSize = "1024x1024" | "1792x1024" | "1024x1792";

export interface ImageGenInput {
  prompt: string;
  size?: ImageSize;
}

/**
 * Model-safe result. Deliberately contains no image bytes — the bytes leave
 * the tool through `extractMedia` only, so they never enter model context.
 */
export interface ImageGenOutput {
  ok: true;
  /** The prompt as sent to the service (trimmed). */
  prompt: string;
  size: ImageSize;
  /** The provider's rewritten prompt, when it returns one. */
  revisedPrompt?: string;
}

export interface ImageGenConfig {
  /** Owner-configured endpoint root, e.g. https://api.openai.com/v1 */
  baseUrl: string;
  apiKey?: string;
  model: string;
}

/** Out-of-band HTTP call, mirroring the pinned transport's shape. */
export interface ImageGenTransport {
  request(opts: {
    url: string;
    headers: Record<string, string>;
    body: string;
    timeoutMs: number;
    signal: AbortSignal;
  }): Promise<{ status: number; body: string }>;
}

export interface ImageGenDeps extends ImageGenConfig {
  /**
   * Test seam. Production always uses the pinned transport; tests inject a
   * stub here so no network is touched. Never model-controlled.
   */
  transport?: ImageGenTransport;
  /** Test seam for DNS, threaded into resolveTarget. */
  resolver?: DnsResolver;
}

/** Per-generation deadline: image rendering is slow, but not unbounded. */
export const GENERATIONS_TIMEOUT_MS = 90_000;

const DEFAULT_SIZE: ImageSize = "1024x1024";
const SIZES: readonly ImageSize[] = ["1024x1024", "1792x1024", "1024x1792"];

/**
 * Whether the tool may be registered. Empty baseUrl means the owner did not
 * configure an image endpoint, so the tool must not exist at all — the model
 * is never told about a tool it cannot use (same pattern as web_search).
 */
export function imageGenConfigured(baseUrl: string): boolean {
  return baseUrl.trim().length > 0;
}

/**
 * Generated image bytes, keyed by the data object `run()` returned.
 *
 * `extractMedia` receives only the data object, and the data contract forbids
 * embedding base64, so the bytes are stashed here by identity instead. The
 * Executor passes the exact object `run()` returned, so the lookup cannot
 * miss; a WeakMap keeps entries from outliving their run.
 */
const mediaBytes = new WeakMap<object, string>();

export function createImageGenTool(deps: ImageGenDeps): Tool<ImageGenInput, ImageGenOutput> {
  if (!imageGenConfigured(deps.baseUrl)) {
    throw new ToolError("disabled", "Image generation is not configured.");
  }

  return {
    name: "generate_image",
    description:
      "Generate an image from a text description. Use it when the user wants an image that does not exist; the user sees the result.",
    enabled: true,
    permission: { requires: [GENERATE_IMAGE_PERMISSION] },
    toolset: "media",
    input: {
      fields: {
        prompt: {
          type: "string",
          required: true,
          description: "Description of the image to generate.",
          minLength: 1,
          maxLength: 1000,
        },
        size: {
          type: "enum",
          description: `Image size (default ${DEFAULT_SIZE}).`,
          choices: [...SIZES],
        },
      },
    },

    extractMedia(data: ImageGenOutput) {
      const b64 = mediaBytes.get(data);
      if (b64 === undefined) return undefined;
      return [{ type: "image", mediaType: "image/png", base64: b64 }];
    },

    async run(input: ImageGenInput, ctx: ToolContext): Promise<ImageGenOutput> {
      const prompt = input.prompt.trim();
      if (prompt.length === 0) {
        throw new ToolError("invalid_input", "Image prompt is empty.");
      }
      if (prompt.length > 1000) {
        // Defence in depth: the field spec caps this first; a direct caller
        // bypassing validation still cannot smuggle a longer prompt through.
        throw new ToolError("invalid_input", "Image prompt is too long.");
      }
      const size: ImageSize = input.size ?? DEFAULT_SIZE;

      // Lexical policy + DNS resolution + address approval, per request.
      // The API key is NOT handed to the guard — only the base URL needs
      // validation; the key travels in the Authorization header below.
      const target = await resolveTarget(
        { baseUrl: deps.baseUrl, apiKey: undefined },
        deps.resolver !== undefined ? { resolver: deps.resolver } : {},
      ).catch((err: unknown) => {
        if (err instanceof AiError) {
          throw new ToolError("invalid_input", "The image service URL is not allowed.");
        }
        throw new ToolError("internal", "Checking the image service URL failed.");
      });

      const body = JSON.stringify({
        model: deps.model,
        prompt,
        n: 1,
        size,
        response_format: "b64_json",
      });

      const headers: Record<string, string> = {
        "content-type": "application/json",
        accept: "application/json",
        "user-agent": "BOBI/0.0.1 (+agent)",
      };
      if (deps.apiKey !== undefined && deps.apiKey.length > 0) {
        headers["authorization"] = `Bearer ${deps.apiKey}`;
      }

      let status: number;
      let rawBody: string;
      try {
        if (deps.transport !== undefined) {
          const res = await deps.transport.request({
            url: `${target.baseUrl}/images/generations`,
            headers,
            body,
            timeoutMs: GENERATIONS_TIMEOUT_MS,
            signal: ctx.signal,
          });
          status = res.status;
          rawBody = res.body;
        } else {
          const res = await pinnedFetch({
            url: `${target.baseUrl}/images/generations`,
            method: "POST",
            headers,
            body,
            timeoutMs: GENERATIONS_TIMEOUT_MS,
            signal: ctx.signal,
            addresses: target.addresses,
            allowLocalTargets: target.allowLocalTargets,
          });
          status = res.status;
          rawBody = res.body;
        }
      } catch (err) {
        // The pinned transport throws AiError with the right category; the
        // test seam throws AiError too, so one mapping covers both.
        if (err instanceof AiError) {
          throw new ToolError(mapAiError(err), messageFor(mapAiError(err)));
        }
        throw new ToolError("internal", "Image generation failed.");
      }

      if (status >= 300 && status < 400) {
        throw new ToolError("invalid_result", "The image service redirected to another address.");
      }
      if (status < 200 || status >= 300) {
        throw statusToError(status);
      }

      const parsed = parseGenerationsResponse(rawBody);
      const data: ImageGenOutput = {
        ok: true,
        prompt,
        size,
        ...(parsed.revisedPrompt !== undefined ? { revisedPrompt: parsed.revisedPrompt } : {}),
      };
      // Bytes ride out-of-band (see extractMedia); `data` stays model-safe.
      mediaBytes.set(data, parsed.b64);
      return data;
    },
  };
}

/** Map an HTTP status onto the tool layer's categories. */
function statusToError(status: number): ToolError {
  if (status === 401 || status === 403) {
    return new ToolError("not_allowed", "The image service key is not valid.");
  }
  if (status === 408) {
    return new ToolError("timeout", "Image generation timed out.");
  }
  if (status === 429) {
    // Back off rather than hammer the service: the agent loop reads
    // "overloaded" as "retry later", not "retry now".
    return new ToolError("overloaded", "The image service is busy; try again shortly.");
  }
  if (status === 400 || status === 404 || status === 422) {
    return new ToolError("invalid_input", "The image generation request was invalid.");
  }
  if (status >= 500) {
    return new ToolError("internal", "The image service is unavailable.");
  }
  return new ToolError("internal", "Image generation failed.");
}

/** Map a transport-level AiError onto the tool layer's categories. */
function mapAiError(err: AiError): ToolError["kind"] {
  switch (err.kind) {
    case "timeout":
    case "aborted":
      return "timeout";
    case "quota":
      return "overloaded";
    case "invalid_response":
      return "invalid_result";
    case "auth":
      return "not_allowed";
    default:
      return "internal";
  }
}

function messageFor(kind: ToolError["kind"]): string {
  switch (kind) {
    case "timeout":
      return "Image generation timed out.";
    case "overloaded":
      return "The image service is busy; try again shortly.";
    case "invalid_result":
      return "The image service response could not be read.";
    case "not_allowed":
      return "The image service key is not valid.";
    default:
      return "Image generation failed.";
  }
}

/**
 * Extract the base64 payload from an images/generations response.
 *
 * Only `b64_json` is accepted: a `url` answer would force a second fetch
 * (more SSRF surface, more failure modes) and is refused outright.
 */
function parseGenerationsResponse(rawBody: string): { b64: string; revisedPrompt?: string } {
  let parsed: unknown;
  try {
    parsed = JSON.parse(rawBody);
  } catch {
    throw new ToolError("invalid_result", "The image service response could not be read.");
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    throw new ToolError("invalid_result", "The image service response could not be read.");
  }
  const data = (parsed as Record<string, unknown>)["data"];
  if (!Array.isArray(data) || data.length === 0) {
    throw new ToolError("invalid_result", "The image service returned no image.");
  }
  const first = data[0];
  if (typeof first !== "object" || first === null || Array.isArray(first)) {
    throw new ToolError("invalid_result", "The image service response could not be read.");
  }
  const rec = first as Record<string, unknown>;
  const b64 = rec["b64_json"];
  if (typeof b64 !== "string" || b64.length === 0) {
    throw new ToolError(
      "invalid_result",
      "The image service did not return the image in the expected format.",
    );
  }
  // Sanity cap: pinnedFetch already bounds the body at 8MB, so this only
  // rejects a response whose data field is implausibly large.
  if (b64.length > 12 * 1024 * 1024) {
    throw new ToolError("invalid_result", "The returned image is too large.");
  }
  const revised = rec["revised_prompt"];
  return {
    b64,
    ...(typeof revised === "string" && revised.length > 0 ? { revisedPrompt: revised } : {}),
  };
}
