export function createVideoGenTool(deps: VideoGenDeps): Tool<VideoGenInput, VideoGenOutput> {
  if (!videoGenConfigured(deps.baseUrl)) {
    throw new ToolError("disabled", "Video generation is not configured.");
  }
  const pollIntervalMs = deps.pollIntervalMs ?? POLL_INTERVAL_MS;
  const maxPollAttempts = deps.maxPollAttempts ?? MAX_POLL_ATTEMPTS;

  return {
    name: "generate_video",
    manifest: generateVideoManifest,
    description:
      "Generate a short video from a text description. Use it when the user wants a video that does not exist; the user sees the result. Generation may take a few minutes.",
    enabled: true,
    permission: { requires: [GENERATE_VIDEO_PERMISSION] },
    toolset: "media",
    input: {
      fields: {
        prompt: {
          type: "string",
          required: true,
          description: "Description of the video to generate.",
          minLength: 1,
          maxLength: 1000,
        },
        size: {
          type: "enum",
          description: `Video size (default ${DEFAULT_SIZE}).`,
          choices: [...SIZES],
        },
        duration_seconds: {
          type: "integer",
          description: `Video length in seconds (default ${DEFAULT_DURATION_SECONDS}).`,
          minimum: MIN_DURATION_SECONDS,
          maximum: MAX_DURATION_SECONDS,
        },
      },
    },
    // Video jobs are slow by design; the executor must not kill the poll loop
    // at its 10s default. Slack past the hard job deadline.
    timeoutMs: VIDEO_JOB_TIMEOUT_MS + 60_000,

    extractMedia(data: VideoGenOutput) {
      const media = mediaBytes.get(data);
      if (media === undefined) return undefined;
      // ContentPart has no "video" kind, so the clip rides as a document —
      // the bot layer delivers it via the same media path as every other
      // tool-produced attachment. A native "video" kind is a follow-up for
      // src/bot/media.ts (owned by another package).
      return [{ type: "document", mediaType: media.mediaType, base64: media.base64, name: media.name }];
    },

    async run(input: VideoGenInput, ctx: ToolContext): Promise<VideoGenOutput> {
      const prompt = input.prompt.trim();
      if (prompt.length === 0) {
        throw new ToolError("invalid_input", "Video prompt is empty.");
      }
      if (prompt.length > 1000) {
        // Defence in depth: the field spec caps this first; a direct caller
        // bypassing validation still cannot smuggle a longer prompt through.
        throw new ToolError("invalid_input", "Video prompt is too long.");
      }
      const size: VideoSize = input.size ?? DEFAULT_SIZE;
      const durationSeconds = input.duration_seconds ?? DEFAULT_DURATION_SECONDS;

      // Lexical policy + DNS resolution + address approval, per request.
      // The API key is NOT handed to the guard — only the base URL needs
      // validation; the key travels in the Authorization header below.
      const target = await resolveTarget(
        { baseUrl: deps.baseUrl, apiKey: undefined },
        deps.resolver !== undefined ? { resolver: deps.resolver } : {},
      ).catch((err: unknown) => {
        if (err instanceof AiError) {
          throw new ToolError("invalid_input", "The video service URL is not allowed.");
        }
        throw new ToolError("internal", "Checking the video service URL failed.");
      });

      const jobId = await submitJob(target.baseUrl, prompt, size, durationSeconds, deps, ctx);
      const video = await pollForVideo(target.baseUrl, jobId, deps, ctx, pollIntervalMs, maxPollAttempts);

      const data: VideoGenOutput = { ok: true, prompt, size, durationSeconds };
      // Bytes ride out-of-band (see extractMedia); `data` stays model-safe.
      mediaBytes.set(data, video);
      return data;
    },
  };
}

/** Common headers for the JSON legs of the job protocol. */
function jsonHeaders(deps: VideoGenDeps): Record<string, string> {
  const headers: Record<string, string> = {
    "content-type": "application/json",
    accept: "application/json",
    "user-agent": "BOBI/0.0.1 (+agent)",
  };
  if (deps.apiKey !== undefined && deps.apiKey.length > 0) {
    headers["authorization"] = `Bearer ${deps.apiKey}`;
  }
  return headers;
}

interface HttpResult {
  status: number;
  body: string;
  rawBody?: Buffer;
}

/**
 * One HTTP leg, through the injected stub in tests or the pinned transport in
 * production. Redirects are never followed (the pinned transport refuses
 * them); a 3xx here is a provider fault, not a follow-me.
 */
async function http(
  opts: {
    url: string;
    method: "GET" | "POST";
    headers: Record<string, string>;
    body: string;
    timeoutMs: number;
  },
  deps: VideoGenDeps,
  ctx: ToolContext,
  addresses?: readonly string[],
  allowLocalTargets?: boolean,
): Promise<HttpResult> {
  try {
    if (deps.transport !== undefined) {
      return await deps.transport.request({ ...opts, signal: ctx.signal });
    }
    const res = await pinnedFetch({
      url: opts.url,
      method: opts.method,
      headers: opts.headers,
      body: opts.body,
      timeoutMs: opts.timeoutMs,
      signal: ctx.signal,
      addresses: addresses ?? [],
      ...(allowLocalTargets !== undefined ? { allowLocalTargets } : {}),
    });
    return { status: res.status, body: res.body, rawBody: res.rawBody };
  } catch (err) {
    // The pinned transport throws AiError with the right category; the test
    // seam throws AiError too, so one mapping covers both.
    if (err instanceof AiError) {
      throw new ToolError(mapAiError(err), messageFor(mapAiError(err)));
    }
    throw new ToolError("internal", "Video generation failed.");
  }
}

/** Submit the job; returns the provider's job id. */
async function submitJob(
  baseUrl: string,
  prompt: string,
  size: VideoSize,
  durationSeconds: number,
  deps: VideoGenDeps,
  ctx: ToolContext,
): Promise<string> {
  const body = JSON.stringify({
    ...(deps.model.length > 0 ? { model: deps.model } : {}),
    prompt,
    n: 1,
    size,
    duration_seconds: durationSeconds,
  });
  const res = await http(
    {
      url: `${baseUrl}/videos/jobs`,
      method: "POST",
      headers: jsonHeaders(deps),
      body,
      timeoutMs: VIDEO_REQUEST_TIMEOUT_MS,
    },
    deps,
    ctx,
  );
  if (res.status >= 300 && res.status < 400) {
    throw new ToolError("invalid_result", "The video service redirected to another address.");
  }
  if (res.status < 200 || res.status >= 300) {
    throw statusToError(res.status);
  }
  const parsed = parseJson(res.body);
  const id = parsed["id"] ?? parsed["job_id"] ?? parsed["request_id"];
  if (typeof id !== "string" || id.length === 0) {
    throw new ToolError("invalid_result", "The video service did not return a job id.");
  }
  return id;
}

/**
 * Poll the status endpoint until the video is ready, the job fails, or a
 * hard cap is hit. The loop is bounded BOTH by a wall-clock deadline and by
 * an attempt cap — whichever trips first ends the run as a timeout.
 */
async function pollForVideo(
  baseUrl: string,
  jobId: string,
  deps: VideoGenDeps,
  ctx: ToolContext,
  pollIntervalMs: number,
  maxPollAttempts: number,
): Promise<{ base64: string; mediaType: string; name: string }> {
  const deadline = Date.now() + VIDEO_JOB_TIMEOUT_MS;
  const statusUrl = `${baseUrl}/videos/jobs/${encodeURIComponent(jobId)}`;

  for (let attempt = 0; attempt < maxPollAttempts; attempt++) {
    if (Date.now() >= deadline) break;
    if (attempt > 0) {
      await sleep(pollIntervalMs, ctx.signal);
    }
    if (Date.now() >= deadline) break;

    const res = await http(
      {
        url: statusUrl,
        method: "GET",
        headers: jsonHeaders(deps),
        body: "",
        timeoutMs: VIDEO_REQUEST_TIMEOUT_MS,
      },
      deps,
      ctx,
    );
    if (res.status >= 300 && res.status < 400) {
      throw new ToolError("invalid_result", "The video service redirected to another address.");
    }
    if (res.status < 200 || res.status >= 300) {
      throw statusToError(res.status);
    }

    const parsed = parseJson(res.body);
    const status = typeof parsed["status"] === "string" ? parsed["status"].toLowerCase() : "";
    if (TERMINAL_FAILURE.has(status)) {
      throw new ToolError("invalid_result", "Video generation failed at the service.");
    }
    if (TERMINAL_SUCCESS.has(status)) {
      return await resolveVideoPayload(parsed, deps, ctx);
    }
    // Anything else (queued/processing/…) → next poll, within the caps.
  }
  throw new ToolError("timeout", "Video generation took too long and was cancelled.");
}

const TERMINAL_SUCCESS = new Set(["succeeded", "completed", "complete", "done"]);
const TERMINAL_FAILURE = new Set(["failed", "error", "cancelled", "canceled"]);

/**
 * Turn a terminal status payload into bytes.
 *
 * Accepts inline base64 or a download URL. A URL is fetched through the SAME
 * guarded transport: the URL is resolved and classified by resolveTarget
 * first, so a provider cannot point the download at an internal host or a
 * non-HTTP scheme.
 */
async function resolveVideoPayload(
  parsed: Record<string, unknown>,
  deps: VideoGenDeps,
  ctx: ToolContext,
): Promise<{ base64: string; mediaType: string; name: string }> {
  const video = parsed["video"] ?? parsed["result"];
  if (typeof video !== "object" || video === null || Array.isArray(video)) {
    throw new ToolError("invalid_result", "The video service returned no video.");
  }
  const rec = video as Record<string, unknown>;

  const b64 = rec["b64"] ?? rec["video_b64"];
  if (typeof b64 === "string" && b64.length > 0) {
    return { base64: checkBudget(b64), mediaType: "video/mp4", name: "bobi.mp4" };
  }

  const url = rec["url"] ?? rec["video_url"];
  if (typeof url === "string" && url.length > 0) {
    return await downloadVideo(url, deps, ctx);
  }
  throw new ToolError("invalid_result", "The video service returned no video.");
}

/** Budget: refuse a payload whose decoded size exceeds the transport ceiling. */
function checkBudget(b64: string): string {
  if (base64Bytes(b64) > MAX_VIDEO_BYTES) {
    throw new ToolError("invalid_result", "The returned video is too large.");
  }
  return b64;
}

/**
 * Download the finished clip from a provider-supplied URL.
 *
 * The URL is provider output, so it is NOT trusted: in production it goes
 * through resolveTarget (lexical policy + DNS classification, no local
 * targets) and pinnedFetch (no redirects, pinned addresses, 8MB body cap)
 * exactly like the job legs. The test seam bypasses resolution the same way
 * the job legs do.
 */
async function downloadVideo(
  url: string,
  deps: VideoGenDeps,
  ctx: ToolContext,
): Promise<{ base64: string; mediaType: string; name: string }> {
  let addresses: readonly string[] | undefined;
  let allowLocalTargets: boolean | undefined;
  if (deps.transport === undefined) {
    const target = await resolveTarget(
      { baseUrl: url, apiKey: undefined },
      deps.resolver !== undefined ? { resolver: deps.resolver } : {},
    ).catch((err: unknown) => {
      if (err instanceof AiError) {
        throw new ToolError("invalid_result", "The video download URL is not allowed.");
      }
      throw new ToolError("internal", "Checking the video download URL failed.");
    });
    addresses = target.addresses;
    allowLocalTargets = target.allowLocalTargets;
  }

  const res = await http(
    {
      url,
      method: "GET",
      headers: {
        accept: "video/*",
        "user-agent": "BOBI/0.0.1 (+agent)",
        ...(deps.apiKey !== undefined && deps.apiKey.length > 0
          ? { authorization: `Bearer ${deps.apiKey}` }
          : {}),
      },
      body: "",
      timeoutMs: VIDEO_REQUEST_TIMEOUT_MS,
    },
    deps,
    ctx,
    addresses,
    allowLocalTargets,
  );
  if (res.status >= 300 && res.status < 400) {
    throw new ToolError("invalid_result", "The video service redirected to another address.");
  }
  if (res.status < 200 || res.status >= 300) {
    throw statusToError(res.status);
  }

  // Prefer the raw bytes: a UTF-8 text decode would corrupt binary video.
  const b64 =
    res.rawBody !== undefined
      ? res.rawBody.toString("base64")
      : Buffer.from(res.body, "utf8").toString("base64");
  if (base64Bytes(b64) === 0) {
    throw new ToolError("invalid_result", "The video service returned no video.");
  }
  const ext = safeExtFromUrl(url);
  return {
    base64: checkBudget(b64),
    mediaType: ext === "webm" ? "video/webm" : ext === "mov" ? "video/quicktime" : "video/mp4",
    name: `bobi.${ext === "webm" ? "webm" : ext === "mov" ? "mov" : "mp4"}`,
  };
}

/**
 * File extension from a provider URL, sanitised — never raw provider input.
 * Unknown extensions fall back to mp4.
 */
function safeExtFromUrl(url: string): string {
  const path = url.split("?")[0]!.split("#")[0]!;
  const tail = path.slice(path.lastIndexOf("/") + 1);
  const dot = tail.lastIndexOf(".");
  const ext = dot >= 0 ? tail.slice(dot + 1).toLowerCase() : "";
  return ext === "mp4" || ext === "webm" || ext === "mov" ? ext : "mp4";
}

/** Parse a JSON body, mapping every fault to invalid_result. */
function parseJson(rawBody: string): Record<string, unknown> {
  let parsed: unknown;
  try {
    parsed = JSON.parse(rawBody);
  } catch {
    throw new ToolError("invalid_result", "The video service response could not be read.");
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    throw new ToolError("invalid_result", "The video service response could not be read.");
  }
  return parsed as Record<string, unknown>;
}

/** Cooperative sleep between polls; aborting the run aborts the wait. */
function sleep(ms: number, signal: AbortSignal): Promise<void> {
  if (ms <= 0) return Promise.resolve();
  return new Promise<void>((resolve, reject) => {
    if (signal.aborted) {
      reject(new AiError("aborted", "Cancelled."));
      return;
    }
    const timer = setTimeout(() => {
      signal.removeEventListener("abort", onAbort);
      resolve();
    }, ms);
    const onAbort = () => {
      clearTimeout(timer);
      reject(new AiError("aborted", "Cancelled."));
    };
    signal.addEventListener("abort", onAbort, { once: true });
  });
}

/** Map an HTTP status onto the tool layer's categories. */
function statusToError(status: number): ToolError {
  if (status === 401 || status === 403) {
    return new ToolError("not_allowed", "The video service key is not valid.");
  }
  if (status === 408) {
    return new ToolError("timeout", "Video generation timed out.");
  }
  if (status === 429) {
    // Back off rather than hammer the service: the agent loop reads
    // "overloaded" as "retry later", not "retry now".
    return new ToolError("overloaded", "The video service is busy; try again shortly.");
  }
  if (status === 400 || status === 404 || status === 422) {
    return new ToolError("invalid_input", "The video generation request was invalid.");
  }
  if (status >= 500) {
    return new ToolError("internal", "The video service is unavailable.");
  }
  return new ToolError("internal", "Video generation failed.");
}

/** Map a transport-level AiError onto the tool layer's categories. */
function mapAiError(err: AiError): ToolError["kind"] {
  switch (err.kind) {
    case "timeout":
    case "aborted":
      return "timeout";
    case "quota":
      return "overloaded";
    case "invalid_response":
      return "invalid_result";
    case "auth":
      return "not_allowed";
    default:
      return "internal";
  }
}

function messageFor(kind: ToolError["kind"]): string {
  switch (kind) {
    case "timeout":
      return "Video generation timed out.";
    case "overloaded":
      return "The video service is busy; try again shortly.";
    case "invalid_result":
      return "The video service response could not be read.";
    case "not_allowed":
      return "The video service key is not valid.";
    default:
      return "Video generation failed.";
  }
}
