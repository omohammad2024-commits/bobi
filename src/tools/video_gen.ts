/**
 * generate_video — render one short video from a text prompt.
 *
 * SECURITY MODEL (read before touching the transport code):
 * - The prompt is USER DATA (model-controlled). It is sent ONLY to the video
 *   endpoint the owner configured (`BOBI_VIDEO_BASE_URL`), never anywhere the
 *   prompt itself could name. The URL is built from the owner config; no part
 *   of the model input can influence the host, path, or scheme.
 * - All HTTP goes through `resolveTarget` + `pinnedFetch`, the same pinned
 *   transport the AI adapters use: DNS is resolved and every address
 *   classified against the SSRF policy before any socket is opened, redirects
 *   are never followed, and the connection is bound to the approved addresses
 *   only. Local/private targets are refused (no local-target opt-in here).
 * - The API key is read from owner config and sent only as an Authorization
 *   header to the configured endpoint. Errors never echo the key or the raw
 *   response body — a provider that echoes the request must not be able to
 *   leak the key into a user-visible message.
 * - Video generation is ASYNC: submit a job, then poll a status endpoint.
 *   When the provider answers with a download URL (rather than inline
 *   base64), that URL is ALSO run through resolveTarget + pinnedFetch before
 *   any byte is fetched — a provider must not be able to steer the download
 *   at an internal address, a metadata endpoint, or a non-HTTP scheme.
 * - The generated bytes are PROVIDER OUTPUT treated as data. They are NEVER
 *   placed in `data` (the model-safe result): the base64 rides out-of-band
 *   via `extractMedia`, which the bot layer delivers to the user. `data`
 *   carries only metadata (prompt, size, duration).
 * - One video per call (n=1), a hard job deadline plus an attempt cap on the
 *   poll loop, per-request deadlines, and HTTP 429 maps to `overloaded` so
 *   the agent loop backs off instead of hammering the service.
 *
 * PROVIDER CONTRACT (the generic shape this tool expects):
 * - Submit: POST {baseUrl}/videos/jobs
 *   body {model?, prompt, n:1, size, duration_seconds}
 *   → 200 {id}            (also accepts "job_id" / "request_id")
 * - Poll:   GET  {baseUrl}/videos/jobs/{id}
 *   → 200 {status, video?}
 *     status: "succeeded" | "completed" | "complete" | "done" → done;
 *             "failed" | "error" | "cancelled" | "canceled"     → terminal failure;
 *             anything else                                    → keep polling.
 * - The video payload, when present, is one of:
 *     {video: {b64: "<base64 mp4>"}}      (also "video_b64")
 *     {video: {url: "https://…"}}         (also "video_url"; downloaded
 *                                          through the guarded transport)
 */
import { resolveTarget, type DnsResolver } from "../ai/dns_guard";
import { pinnedFetch, MAX_RESPONSE_BYTES } from "../ai/pinned_transport";
import { AiError, base64Bytes } from "../ai/provider";
import { processEnv, readChained } from "../config/env";
import { ToolError } from "./errors";
import type { Tool, ToolContext } from "./types";
import { defineManifest } from "./manifest";
import type { ToolManifest } from "./manifest";

export const GENERATE_VIDEO_PERMISSION = "tools:generate_video";

/** Sizes the video endpoint accepts. */
export type VideoSize = "1280x720" | "720x1280";

export interface VideoGenInput {
  prompt: string;
  size?: VideoSize;
  /** Clip length in seconds. */
  duration_seconds?: number;
}

/**
 * Model-safe result. Deliberately contains no video bytes — the bytes leave
 * the tool through `extractMedia` only, so they never enter model context.
 */
export interface VideoGenOutput {
  ok: true;
  /** The prompt as sent to the service (trimmed). */
  prompt: string;
  size: VideoSize;
  /** Clip length in seconds, as requested. */
  durationSeconds: number;
}

export interface VideoGenConfig {
  /** Owner-configured endpoint root, e.g. https://queue.fal.run */
  baseUrl: string;
  apiKey?: string;
  /** Optional; omitted from the submit body when empty. */
  model: string;
}

/** Out-of-band HTTP call, mirroring the pinned transport's shape. */
export interface VideoGenTransport {
  request(opts: {
    url: string;
    /** Defaults to "POST"; the download leg uses "GET". */
    method?: "GET" | "POST";
    headers: Record<string, string>;
    body: string;
    timeoutMs: number;
    signal: AbortSignal;
  }): Promise<{ status: number; body: string; rawBody?: Buffer }>;
}

export interface VideoGenDeps extends VideoGenConfig {
  /**
   * Test seam. Production always uses the pinned transport; tests inject a
   * stub here so no network is touched. Never model-controlled.
   */
  transport?: VideoGenTransport;
  /** Test seam for DNS, threaded into resolveTarget. */
  resolver?: DnsResolver;
  /**
   * Test seam: delay between status polls. Production waits
   * POLL_INTERVAL_MS; tests pass ~1ms so the loop stays fast.
   */
  pollIntervalMs?: number;
  /** Test seam: hard cap on poll attempts. Production uses MAX_POLL_ATTEMPTS. */
  maxPollAttempts?: number;
}

/** Hard deadline for one video job, submit → finished video. */
export const VIDEO_JOB_TIMEOUT_MS = 10 * 60 * 1000;

/** Per-request deadline for submit/poll/download legs. */
export const VIDEO_REQUEST_TIMEOUT_MS = 30_000;

/** Delay between status polls in production. */
export const POLL_INTERVAL_MS = 5_000;

/** Hard cap on poll attempts: the loop ends on deadline OR attempt cap. */
export const MAX_POLL_ATTEMPTS = 120;

/** Budget: a video larger than the pinned transport's response ceiling is refused. */
export const MAX_VIDEO_BYTES = MAX_RESPONSE_BYTES;

const DEFAULT_SIZE: VideoSize = "1280x720";
const SIZES: readonly VideoSize[] = ["1280x720", "720x1280"];
const DEFAULT_DURATION_SECONDS = 5;
const MIN_DURATION_SECONDS = 1;
const MAX_DURATION_SECONDS = 30;

/**
 * Whether the tool may be registered. Empty baseUrl means the owner did not
 * configure a video endpoint, so the tool must not exist at all — the model
 * is never told about a tool it cannot use (same pattern as web_search and
 * generate_image).
 */
export function videoGenConfigured(baseUrl: string): boolean {
  return baseUrl.trim().length > 0;
}

/**
 * Read this tool's config straight from the environment.
 *
 * The video tool reads its own keys instead of adding fields to the shared
 * SolConfig: BOBI_VIDEO_* with the same SOL_VIDEO_* fallback the shared
 * config loader honours — and NO bare-name step. Phase 7: the chain is the
 * shared "prefixed" chain in src/config/env.ts.
 */
export function videoGenDepsFromEnv(env: NodeJS.ProcessEnv = processEnv()): {
  baseUrl: string;
  apiKey?: string;
  model: string;
} {
  const pick = (suffix: string): string | undefined =>
    readChained(env, suffix, "prefixed");
  const baseUrl = (pick("VIDEO_BASE_URL") ?? "").trim();
  const apiKey = pick("VIDEO_API_KEY")?.trim() || undefined;
  const model = (pick("VIDEO_MODEL") ?? "").trim();
  return {
    baseUrl,
    ...(apiKey !== undefined ? { apiKey } : {}),
    model,
  };
}

/**
 * Generated video bytes, keyed by the data object `run()` returned.
 *
 * `extractMedia` receives only the data object, and the data contract forbids
 * embedding base64, so the bytes are stashed here by identity instead. The
 * Executor passes the exact object `run()` returned, so the lookup cannot
 * miss; a WeakMap keeps entries from outliving their run.
 */
const mediaBytes = new WeakMap<object, { base64: string; mediaType: string; name: string }>();

